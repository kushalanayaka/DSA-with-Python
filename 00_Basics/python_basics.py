# Python Basics for DSA

# Variables
x = 10
name = "Python"

# Data types
a = 5          # int
b = 3.14       # float
c = "DSA"      # string
d = True       # boolean

# Lists (most used in DSA)
arr = [1, 2, 3, 4, 5]

# Loop
for i in arr:
    print(i)

# Function
def add(a, b):
    return a + b

print(add(2, 3))

# Condition
n = 10
if n % 2 == 0:
    print("Even")
else:
    print("Odd")
